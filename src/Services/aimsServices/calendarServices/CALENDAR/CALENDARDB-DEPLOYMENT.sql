-- Procedure: usp_CreateShift
CREATE OR ALTER PROCEDURE dbo.usp_CreateShift
(
    @p_Code VARCHAR(20),
    @p_Name VARCHAR(255),
    @p_InTime TIME,
    @p_OutTime TIME,
    @p_CreatedBy BIGINT,
    @p_ShiftID INT OUTPUT
)
AS
BEGIN
    SET NOCOUNT ON;
    BEGIN TRY
        BEGIN TRANSACTION;
        
        IF EXISTS (SELECT 1 FROM SHIFT_MASTER WHERE SHIFT_CODE = @p_Code)
            THROW 50001, 'Shift code already exists', 1;
        
        DECLARE @Duration DECIMAL(5,2);
        SET @Duration = CAST(DATEDIFF(MINUTE, @p_InTime, @p_OutTime) AS DECIMAL(5,2)) / 60;
        
        SELECT @p_ShiftID = ISNULL(MAX(SHIFT_ID), 0) + 1 FROM SHIFT_MASTER;
        
        INSERT INTO SHIFT_MASTER
        (SHIFT_ID, SHIFT_CODE, SHIFT_NAME, SHIFT_INTIME, SHIFT_OUTTIME, SHIFT_DURATION, SHIFT_LASTMODIFIEDBY, SHIFT_LASTMODIFIEDON)
        VALUES (@p_ShiftID, @p_Code, @p_Name, @p_InTime, @p_OutTime, @Duration, @p_CreatedBy, GETDATE());
        
        COMMIT TRANSACTION;
        PRINT 'Shift created: ID = ' + CAST(@p_ShiftID AS VARCHAR);
    END TRY
    BEGIN CATCH
        IF @@TRANCOUNT > 0 ROLLBACK TRANSACTION;
        RAISERROR('Shift creation failed: %s', 16, 1, ERROR_MESSAGE());
    END CATCH
END;
GO

