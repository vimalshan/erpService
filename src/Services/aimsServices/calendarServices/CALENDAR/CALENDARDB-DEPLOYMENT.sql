    @p_Type CHAR(1),
    @p_CreatedBy BIGINT,
    @p_HolidayID INT OUTPUT
)
AS
BEGIN
    SET NOCOUNT ON;
    BEGIN TRY
        BEGIN TRANSACTION;
        
        IF @p_Type NOT IN ('N', 'O')
            THROW 50002, 'Holiday type must be N (National) or O (Optional)', 1;
        
        SELECT @p_HolidayID = ISNULL(MAX(HOLIDAY_ID), 0) + 1 FROM HOLIDAY_MASTER;
        
