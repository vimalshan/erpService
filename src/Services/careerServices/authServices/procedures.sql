/****** SP_GET_PASSWORD ******/
SET ANSI_NULLS ON
GO
SET QUOTED_IDENTIFIER ON
GO
CREATE PROCEDURE [dbo].[SP_GET_PASSWORD] 
(
@PERSONAL_MAIID varchar(50),
@DATE_OF_BIRTH DATETIME,
@STATUS varchar(40) output
)
AS
BEGIN

IF EXISTS (SELECT LOGIN_ID from REGISTRATION_TABLE where PERSONAL_MAIID=@PERSONAL_MAIID and ISVALID=1)
	begin
	
	if Exists (SELECT * from REGISTRATION_TABLE INNER JOIN PERSONAL_DETAILS on REGISTRATION_TABLE.LOGIN_ID=PERSONAL_DETAILS.LOGIN_ID where REGISTRATION_TABLE.PERSONAL_MAIID=@PERSONAL_MAIID and PERSONAL_DETAILS.DATE_OF_BIRTH=@DATE_OF_BIRTH  and REGISTRATION_TABLE.ISVALID=1)
		begin
		--SELECT * from spa_user where userid=@userid and password=@password--
		set @STATUS=(SELECT REGISTRATION_TABLE.PASSWORD from REGISTRATION_TABLE INNER JOIN PERSONAL_DETAILS on REGISTRATION_TABLE.LOGIN_ID=PERSONAL_DETAILS.LOGIN_ID where REGISTRATION_TABLE.PERSONAL_MAIID=@PERSONAL_MAIID and PERSONAL_DETAILS.DATE_OF_BIRTH=@DATE_OF_BIRTH  and REGISTRATION_TABLE.ISVALID=1)
		end
	else
		begin
		set @STATUS='Invalid Date of Birth..'
		end
	
	end
else
	begin
	set @STATUS='Invalid User Id..'
	end
	
END
GO

