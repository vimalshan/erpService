    [CPN_REF_ID] VARCHAR(25) NULL,
    [CPN_REQ_ID] BIGINT NULL,
    [CPN_NOF_TCK] BIGINT NULL,
    [CPN_ARL_NAM] CHAR(3) NULL,
    [CPN_CUP_STR] BIGINT NULL,
    [CPN_CUP_END] BIGINT NULL,
    [CPN_VLD_FRM] DATETIME2(3) NULL,
    [CPN_VLD_TO] DATETIME2(3) NULL,
    [CPN_CUP_CST] BIGINT NULL,
    [CPN_ISE_REK] VARCHAR(500) NULL,
    [CPN_USG_FLG] CHAR(1) NULL,
    [CPN_USR_ID] VARCHAR(50) NULL,
    [CPN_USR_PIN] BIGINT NULL,
    [CPN_ADN_USR] VARCHAR(50) NULL,
    [CPN_ADN_UNT] CHAR(5) NULL,
    [CPN_ISS_DAT] DATETIME2(3) NULL,
    [CPN_FLX_FLD1] BIGINT NULL,
    [CPN_FLX_FLD2] VARCHAR(25) NULL,
    [CPN_FLX_FLD3] DATETIME2(3) NULL,
    [CPN_FLX_FLD] CHAR(5) NULL,
    CONSTRAINT [PK_COUPON_MAIN] PRIMARY KEY ([CPN_CUP_ID])
);

-- Table: COUPON_SUB - Coupon ticket details
CREATE TABLE [COUPON_SUB] (
    [CPN_CUP_ID] BIGINT NULL,
    [CPN_SRL_NUM] BIGINT NULL,
    [CPN_TCK_NUM] VARCHAR(20) NULL,
    [CPN_USG_FLG] CHAR(1) NULL
);

-- Table: CABPICK - Cab pickup configuration
CREATE TABLE [CABPICK] (
    [CITYFROM] VARCHAR(25) NULL,
    [CITYTO] VARCHAR(25) NULL,
    [PICKFLAG] VARCHAR(4) NULL
);

-- Table: ROOMAVAIL_TEMP - Temporary room availability
