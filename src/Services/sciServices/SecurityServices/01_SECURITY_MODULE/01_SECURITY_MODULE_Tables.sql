    [UM_DEPT_COD] VARCHAR(25) NOT NULL,
    [UM_STR_DAT] DATETIME2(3) NOT NULL,
    [UM_END_DAT] DATETIME2(3) NULL,
    CONSTRAINT [PK_USER_MASTER_MAP] PRIMARY KEY ([UM_MAP_ID])
