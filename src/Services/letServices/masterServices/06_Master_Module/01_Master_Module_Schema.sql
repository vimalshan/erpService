CREATE INDEX [IDX_FUNCTION_MAST_GRP_COD] ON [FUNCTION_MAST]([FN_GRP_COD]);
CREATE INDEX [IDX_JOB_MAST_CAT_COD] ON [JOB_MAST]([JB_CAT_COD]);
