    [ENV_ID] BIGINT NOT NULL,
    [ENV_TYPE] CHAR(3) NOT NULL,
    [ENV_CREATEDBY] BIGINT NOT NULL,
    [ENV_CREATEDON] DATETIME2(3) NOT NULL,
    [ENV_RECEIVEDBY] BIGINT NULL,
    [ENV_RECEIVEDON] DATETIME2(3) NULL,
    [ENV_SUMMARYFLAG] CHAR(1) NOT NULL,
    [ENV_CANCELLEDBY] BIGINT NULL,
    [ENV_CANCELLEDON] DATETIME2(3) NULL,
    [ENV_CONFIRMEDBY] BIGINT NULL,
    [ENV_CONFIRMEDON] DATETIME2(3) NULL,
    [ENV_SCANLOTNO] BIGINT NULL,
    [ENV_LOCID] BIGINT NOT NULL,
    CONSTRAINT [PK_ENV_MAIN] PRIMARY KEY ([ENV_ID])
);
GO

-- ==========================================
-- SCAN_LOTMAST - Scan Lot Master
-- ==========================================
IF OBJECT_ID('[SCAN_LOTMAST]', 'U') IS NOT NULL DROP TABLE [SCAN_LOTMAST];
GO
CREATE TABLE [SCAN_LOTMAST] (
    [SCAN_LOTNO] BIGINT NOT NULL,
    [SCAN_USERID] BIGINT NOT NULL,
    [SCAN_STATUS] CHAR(1) NOT NULL,
    [SCAN_DEVICENO] INT NOT NULL,
    [SCAN_CLOSEDATE] DATETIME2(3) NULL,
