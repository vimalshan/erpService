-- ==========================================
-- ENV_RECDET - Envelope Receipt Details
-- ==========================================
IF OBJECT_ID('[ENV_RECDET]', 'U') IS NOT NULL DROP TABLE [ENV_RECDET];
GO
CREATE TABLE [ENV_RECDET] (
    [REC_ID] BIGINT NOT NULL,
    [REC_ENVID] BIGINT NOT NULL,
    [REC_DOCID] BIGINT NOT NULL,
    [REC_UPDATEDBY] BIGINT NOT NULL,
    [REC_UPDATEDON] DATETIME2(3) NOT NULL,
    [REC_ENVTYPE] CHAR(3) NULL,
    [REC_SCANLOCATIONID] BIGINT NULL,
    CONSTRAINT [PK_ENV_RECDET] PRIMARY KEY ([REC_ID])
