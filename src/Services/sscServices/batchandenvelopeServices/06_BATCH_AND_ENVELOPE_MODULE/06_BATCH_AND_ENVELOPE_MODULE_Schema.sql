USE SSCDB;
GO

-- ==========================================
-- BATCH_MAIN - Batch Master
-- ==========================================
IF OBJECT_ID('[BATCH_MAIN]', 'U') IS NOT NULL DROP TABLE [BATCH_MAIN];
GO
CREATE TABLE [BATCH_MAIN] (
    [BATCH_ID] BIGINT NOT NULL,
    [BATCH_CREATEDBY] BIGINT NOT NULL,
    [BATCH_CREATEDON] DATETIME2(3) NOT NULL,
    [BATCH_LOCATIONID] BIGINT NOT NULL,
    [BATCH_RECEIVEDBY] BIGINT NOT NULL,
    [BATCH_RECEIVEDON] DATETIME2(3) NOT NULL,
    [BATCH_PODNO] VARCHAR(25) NOT NULL,
    [BATCH_SUMMARYFLAG] CHAR(1) NOT NULL,
    [BATCH_CANCELBY] BIGINT NULL,
    [BATCH_CANCELDATE] DATETIME2(3) NULL,
    [BATCH_CONFIRMEDBY] BIGINT NULL,
    [BATCH_CONFIRMEDON] DATETIME2(3) NULL,
    [BATCH_COURIERNAME] VARCHAR(100) NULL,
    [BATCH_SCANFLAG] VARCHAR(25) NOT NULL,
    CONSTRAINT [PK_BATCH_MAIN] PRIMARY KEY ([BATCH_ID])
);
GO

-- ==========================================
-- BATCH_DET - Batch Details
-- ==========================================
IF OBJECT_ID('[BATCH_DET]', 'U') IS NOT NULL DROP TABLE [BATCH_DET];
GO
CREATE TABLE [BATCH_DET] (
    [BATCH_DETID] INT NOT NULL,
    [BATCH_ID] BIGINT NOT NULL,
    [BATCH_ENVID] INT NOT NULL,
    [BATCH_CREATEDBY] BIGINT NOT NULL,
    [BATCH_CREATEDON] DATETIME2(3) NOT NULL,
    [BATCH_RECEIVEFLAG] CHAR(1) NOT NULL,
    [BATCH_RECEIVEDBY] BIGINT NULL,
    [BATCH_RECEIVEDON] DATETIME2(3) NULL,
    [BATCH_CANCELDATE] DATETIME2(3) NOT NULL,
    [BATCH_CANCELBY] BIGINT NOT NULL,
    CONSTRAINT [PK_BATCH_DET] PRIMARY KEY ([BATCH_DETID])
);
GO

-- ==========================================
-- BATCH_RECDET - Batch Receipt Details
-- ==========================================
IF OBJECT_ID('[BATCH_RECDET]', 'U') IS NOT NULL DROP TABLE [BATCH_RECDET];
GO
CREATE TABLE [BATCH_RECDET] (
    [REC_ID] BIGINT NOT NULL,
    [REC_BATCHID] BIGINT NOT NULL,
    [REC_ENVID] BIGINT NOT NULL,
    [REC_UPDATEDBY] BIGINT NOT NULL,
    [REC_UPDATEDON] DATETIME2(3) NOT NULL,
    [REC_SCANLOCATIONID] BIGINT NULL,
    CONSTRAINT [PK_BATCH_RECDET] PRIMARY KEY ([REC_ID])
);
GO

-- ==========================================
-- ENV_MAIN - Envelope Master
-- ==========================================
