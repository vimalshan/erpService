using OrganizationSetup.Domain.Common;

namespace OrganizationSetup.Domain.Events;

public sealed record RoleCreatedEvent(long RoleId, string RoleName) : IDomainEvent
{
    public Guid EventId { get; } = Guid.NewGuid();
    public DateTime OccurredOn { get; } = DateTime.UtcNow;
}

public sealed record RoleUpdatedEvent(long RoleId, string RoleName) : IDomainEvent
{
    public Guid EventId { get; } = Guid.NewGuid();
    public DateTime OccurredOn { get; } = DateTime.UtcNow;
}

public sealed record RoleDeletedEvent(long RoleId) : IDomainEvent
{
    public Guid EventId { get; } = Guid.NewGuid();
    public DateTime OccurredOn { get; } = DateTime.UtcNow;
}
